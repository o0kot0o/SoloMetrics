<#
.SYNOPSIS
  Regenerates addon\SoloMetrics\Assets\TextureIndex.lua from the .tga files in
  addon\SoloMetrics\Assets\Textures\Custom (WoW addons cannot list folders at
  runtime, so the list is generated here, in the project, before deploying).

.DESCRIPTION
  Each texture must be an uncompressed or RLE TGA with power-of-two width and
  height. Names: SMTex_BrushedMetal.tga -> key "smtex_brushedmetal",
  label "Brushed Metal". Run this after adding/removing textures, then deploy
  and restart WoW (new files are not picked up by /reload).
  Validate-SoloMetrics.ps1 fails if the index is out of date.
#>
[CmdletBinding()]
param()

Set-StrictMode -Version 2.0
$ErrorActionPreference = 'Stop'

$ProjectRoot = Split-Path -Parent $PSScriptRoot
$Source = Join-Path $ProjectRoot 'addon\SoloMetrics'
$CustomDir = Join-Path $Source 'Assets\Textures\Custom'
$IndexPath = Join-Path $Source 'Assets\TextureIndex.lua'

function Get-TgaInfo([string]$Path) {
    $fs = [System.IO.File]::OpenRead($Path)
    try {
        $h = New-Object byte[] 18
        if ($fs.Read($h, 0, 18) -ne 18) { return $null }
    } finally { $fs.Close() }
    return [pscustomobject]@{
        Type = $h[2]; Width = $h[12] + 256 * $h[13]; Height = $h[14] + 256 * $h[15]; Bpp = $h[16]
    }
}

function Test-Pow2([int]$n) { return $n -gt 0 -and (($n -band ($n - 1)) -eq 0) }

function Get-Label([string]$base) {
    $name = $base -replace '^SMTex_', ''
    $name = $name -creplace '([a-z0-9])([A-Z])', '$1 $2'
    return ($name -replace '[_\-]+', ' ').Trim()
}

$entries = @()
if (Test-Path -LiteralPath $CustomDir) {
    foreach ($f in (Get-ChildItem -LiteralPath $CustomDir -Filter '*.tga' -File | Sort-Object Name)) {
        if ($f.BaseName -notmatch '^[A-Za-z0-9_\-]+$') { throw "Unsupported characters in file name: $($f.Name)" }
        $info = Get-TgaInfo $f.FullName
        if (-not $info -or ($info.Type -ne 2 -and $info.Type -ne 10)) { throw "$($f.Name): not an uncompressed/RLE true-color TGA" }
        if (-not (Test-Pow2 $info.Width) -or -not (Test-Pow2 $info.Height)) {
            throw "$($f.Name): $($info.Width)x$($info.Height) is not power-of-two (e.g. 512x128)"
        }
        $entries += [pscustomobject]@{ Key = $f.BaseName.ToLowerInvariant(); Label = (Get-Label $f.BaseName); File = $f.BaseName }
    }
}

$lines = @(
    '-- GENERATED by scripts/Update-TextureIndex.ps1 - do not edit by hand.',
    '-- Lists Assets/Textures/Custom/*.tga for the texture selector.',
    'local _, ns = ...',
    'ns.CUSTOM_TEXTURES = {'
)
foreach ($e in $entries) {
    $lines += ('    {{ key = "{0}", label = "{1}", file = "{2}" }},' -f $e.Key, $e.Label, $e.File)
}
$lines += '}'

$content = ($lines -join "`n") + "`n"
$existing = if (Test-Path -LiteralPath $IndexPath) { [System.IO.File]::ReadAllText($IndexPath) } else { '' }
if ($existing -ceq $content) {
    Write-Host "TextureIndex.lua up to date ($($entries.Count) textures)."
} else {
    [System.IO.File]::WriteAllText($IndexPath, $content, (New-Object System.Text.UTF8Encoding($false)))
    Write-Host "TextureIndex.lua written ($($entries.Count) textures)." -ForegroundColor Green
}
foreach ($e in $entries) { Write-Host ("  {0,-22} {1}" -f $e.Key, $e.Label) }
